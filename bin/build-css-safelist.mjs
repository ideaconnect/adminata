/*
 * Generates `assets/css/safelist.css` and `assets/css/contract.json` from the component layer.
 *
 * Tailwind emits an `@utility` only when it sees the name in a scanned source (PLAN/04 §4 T1), and
 * adminata's markup is spread across Twig templates in seven packages and, for an application that
 * compiles Tailwind itself, its own. Naming every `.adm-*` in `@source inline()` is what keeps a
 * component from silently disappearing because the one template using it has not been ported yet.
 *
 * The grid ranges are there for the class strings the PHP layer produces: a group's `class` option
 * and the dashboard block's, which default to `col-span-12` and `md:col-span-4` and which an admin
 * class can set to anything.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const componentsDir = fileURLToPath(new URL('../assets/css/components', import.meta.url));
const safelistFile = fileURLToPath(new URL('../assets/css/safelist.css', import.meta.url));
const contractFile = fileURLToPath(new URL('../assets/css/contract.json', import.meta.url));

/** Every `@utility <name>` the component layer declares. */
const utilities = new Set();

/** Every class selector the component layer styles through a descendant rule. */
const selectors = new Set();

for (const file of readdirSync(componentsDir).sort()) {
    if (!file.endsWith('.css')) {
        continue;
    }

    const css = readFileSync(join(componentsDir, file), 'utf8');

    for (const [, name] of css.matchAll(/@utility\s+([a-z][a-z0-9-]*(?:__[a-z0-9-]+)?)\s*\{/g)) {
        utilities.add(name);
    }

    for (const [, name] of css.matchAll(/\.(adm-[a-z0-9-]+(?:__[a-z0-9-]+)?)/g)) {
        selectors.add(name);
    }
}

const names = [...utilities].sort();

const safelist = `/*
 * GENERATED by bin/build-css-safelist.mjs — do not edit.
 *
 * Every component name, so Tailwind emits it whether or not a template mentions it yet, plus the
 * grid classes the PHP layer produces at runtime.
 */

@source inline("{${names.join(',')}}");

/* The add block's column count, composed from \`dropdown_number_groups_per_colums\`. */
@source inline("grid-cols-{1..6}");

/* Group and dashboard-block classes: \`col-span-N\` at every breakpoint, and offsets. */
@source inline("{,sm:,md:,lg:,xl:}col-span-{1..12}");
@source inline("{sm:,md:,lg:,xl:}col-start-{2..12}");

/* \`row_attr\`/\`attr\` users toggling visibility per breakpoint. */
@source inline("{,sm:,md:,lg:}hidden");
@source inline("{sm:,md:,lg:}block");
`;

writeFileSync(safelistFile, safelist);

const contract = {
    _comment:
        'GENERATED by bin/build-css-safelist.mjs. Every selector here must exist in the built app.css; bin/check-css-contract.mjs asserts it.',
    selectors: [
        ...new Set([...names.map((name) => `.${name}`), ...[...selectors].map((name) => `.${name}`)]),
    ].sort(),
};

writeFileSync(contractFile, `${JSON.stringify(contract, null, 4)}\n`);

console.log(
    `Safelisted ${names.length} component names; contract lists ${contract.selectors.length} selectors.`,
);
