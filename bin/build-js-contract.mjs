/*
 * Writes `assets/js/__contract__/controllers.json` from the registry: for every controller, the
 * identifier and the targets, values, classes and outlets its markup may use.
 *
 * That is the JavaScript half of PLAN/02: an application's templates and an application's own
 * Stimulus controllers address adminata through these names, so removing one is a major release.
 * `controllers.test.js` compares the built bundle against this file.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The readmore controller creates one shared ResizeObserver at module scope, so importing the
// registry outside a browser needs it to exist. Nothing here observes anything.
globalThis.ResizeObserver ??= class {
    observe() {}
    unobserve() {}
    disconnect() {}
};

const { controllers } = await import('../assets/js/registry.js');

const contract = {
    _comment:
        'GENERATED by bin/build-js-contract.mjs. The Stimulus surface adminata promises: identifiers, targets, values, classes and outlets. See PLAN/02 §9.',
    controllers: Object.fromEntries(
        Object.entries(controllers)
            .sort(([a], [b]) => a.localeCompare(b))
            .map(([identifier, controller]) => [
                identifier,
                {
                    targets: [...(controller.targets ?? [])].sort(),
                    values: Object.keys(controller.values ?? {}).sort(),
                    classes: [...(controller.classes ?? [])].sort(),
                    outlets: [...(controller.outlets ?? [])].sort(),
                },
            ]),
    ),
};

writeFileSync(
    fileURLToPath(new URL('../assets/js/__contract__/controllers.json', import.meta.url)),
    `${JSON.stringify(contract, null, 4)}\n`,
);

console.log(`Recorded ${Object.keys(contract.controllers).length} controllers.`);
